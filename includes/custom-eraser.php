/**
 * Register a custom eraser for the user custom fields.
 *
 * @param array $erasers
 * @return array
 */
function wpumpd_plugin_register_erasers( $erasers = array() ) {

	$erasers[] = array(
		'eraser_friendly_name' => esc_html__( 'Additional account details', 'wpum-personal-data' ),
		'callback'             => 'wpumpd_plugin_user_data_eraser',
	);

	return $erasers;

}
add_filter( 'wp_privacy_personal_data_erasers', 'wpumpd_plugin_register_erasers' );

/**
 * Everything of a member's the eraser removes: the custom fields WPUM generated, and the profile
 * picture and cover. Other primary fields are the account itself, which an erasure leaves alone.
 *
 * @return array[] Each with the name to report, the meta key, and the meta key of the uploaded
 *                 file's path if it has one.
 */
function wpumpd_get_erasable_items() {

	$items = array();

	$fields = WPUM()->fields->get_fields(
		[
			'orderby' => 'field_order',
			'order'   => 'ASC',
		]
	);

	if ( is_array( $fields ) && ! empty( $fields ) ) {
		foreach ( $fields as $field ) {
			if ( $field->is_primary() ) {
				continue;
			}

			$key = $field->get_meta( 'user_meta_key' );

			$items[] = array(
				'name'     => $field->get_name(),
				'key'      => $key,
				'path_key' => 'file' === $field->get_type() ? $key . '_path' : '',
			);
		}
	}

	$items[] = array(
		'name'     => esc_html__( 'User avatar', 'wpum-personal-data' ),
		'key'      => 'current_user_avatar',
		'path_key' => '_current_user_avatar_path',
	);

	$items[] = array(
		'name'     => esc_html__( 'User profile cover', 'wpum-personal-data' ),
		'key'      => 'user_cover',
		'path_key' => '_user_cover_path',
	);

	return $items;
}

/**
 * The host and port of a URL parsed with wp_parse_url().
 *
 * @param array|false $parts
 * @return string
 */
function wpumpd_get_url_host( $parts ) {
	$host = isset( $parts['host'] ) ? strtolower( $parts['host'] ) : '';
	$port = isset( $parts['port'] ) ? ':' . $parts['port'] : '';

	return $host . $port;
}

/**
 * Remove a file a member uploaded, if it can safely be removed: it has to be inside the uploads
 * folder, be exactly the file the stored URL points to, and not be used by anyone or anything else.
 * Call this once the member's own meta has gone, so it no longer counts as a use of the file.
 *
 * @param string $url  The stored value. Rows of a repeater hold text as well as URLs.
 * @param string $path The stored path of the upload. Repeaters don't record one.
 * @return bool True if nothing of this value is left in the uploads folder.
 */
function wpumpd_erase_file( $url, $path ) {
	global $wpdb;

	$uploads      = wp_get_upload_dir();
	$uploads_url  = wp_parse_url( $uploads['baseurl'] );
	$uploads_path = trailingslashit( isset( $uploads_url['path'] ) ? rawurldecode( $uploads_url['path'] ) : '' );
	$stored_url   = wp_parse_url( $url );
	$stored_path  = isset( $stored_url['path'] ) ? rawurldecode( $stored_url['path'] ) : '';

	// With no path on record there's no telling whose file this is, so it isn't ours to delete.
	if ( empty( $path ) ) {
		return 0 !== strpos( $stored_path, $uploads_path );
	}

	if ( ! file_exists( $path ) ) {
		return true;
	}

	$base = trailingslashit( wp_normalize_path( (string) realpath( $uploads['basedir'] ) ) );
	$file = wp_normalize_path( (string) realpath( $path ) );

	if ( '/' === $base || 0 !== strpos( $file, $base ) || ! is_file( $file ) ) {
		return false;
	}

	$relative = substr( $file, strlen( $base ) );

	if ( $uploads_path . $relative !== $stored_path || wpumpd_get_url_host( $uploads_url ) !== wpumpd_get_url_host( $stored_url ) ) {
		return false;
	}

	// By the file's own address, as a stored URL can be encoded or carry a query string.
	if ( attachment_url_to_postid( trailingslashit( $uploads['baseurl'] ) . $relative ) ) {
		return false;
	}

	// Matches a URL or a path to the file, on its own or inside a serialized value. Anything a URL
	// could encode is a wildcard, so this finds the file however a reference writes its name.
	$pieces  = preg_split( '/[^A-Za-z0-9._~-]+/', $relative );
	$pattern = '%' . implode( '%', array_map( array( $wpdb, 'esc_like' ), $pieces ) ) . '%';

	$in_use = $wpdb->get_var( $wpdb->prepare( "SELECT COUNT(*) FROM {$wpdb->usermeta} WHERE meta_value LIKE %s", $pattern ) ); // phpcs:ignore

	// Null means the check itself failed, and a file that can't be checked stays.
	if ( null === $in_use || $in_use ) {
		return false;
	}

	wp_delete_file( $file );

	return ! file_exists( $file );
}

/**
 * Function that erases the values submitted through custom fields generated by WPUM, the profile
 * picture and cover, and the files uploaded to them.
 *
 * @param string $email_address
 * @param integer $page
 * @return array
 */
function wpumpd_plugin_user_data_eraser( $email_address, $page = 1 ) {

	if ( empty( $email_address ) ) {
		return array(
			'items_removed'  => false,
			'items_retained' => false,
			'messages'       => array(),
			'done'           => true,
		);
	}

	$user = get_user_by( 'email', $email_address );

	$messages       = array();
	$items_removed  = false;
	$items_retained = false;

	if ( $user && $user->ID ) {

		$files = array();

		foreach ( wpumpd_get_erasable_items() as $item ) {

			$keys = array();
			foreach ( array( $item['key'], $item['path_key'] ) as $key ) {
				if ( $key && metadata_exists( 'user', $user->ID, $key ) ) {
					$keys[] = $key;
				}
			}

			if ( empty( $keys ) ) {
				continue;
			}

			$value = get_user_meta( $user->ID, $item['key'], true );
			$path  = $item['path_key'] ? get_user_meta( $user->ID, $item['path_key'], true ) : '';

			// Stop at the first failure: a retry needs the value and path that are left.
			$removed = true;
			foreach ( $keys as $key ) {
				if ( ! delete_user_meta( $user->ID, $key ) ) {
					$removed = false;
					break;
				}
			}

			if ( ! $removed ) {
				// translators: %s field name
				$messages[]     = sprintf( esc_html__( 'Your "%s" was unable to be removed at this time.', 'wpum-personal-data' ), $item['name'] );
				$items_retained = true;
				continue;
			}

			if ( ( '' !== $value && array() !== $value ) || ! empty( $path ) ) {
				$items_removed = true;
			}

			$urls = (array) $value;
			array_walk_recursive(
				$urls,
				function ( $url ) use ( &$files, $item, $path ) {
					if ( is_string( $url ) ) {
						$files[] = array(
							'name' => $item['name'],
							'url'  => $url,
							'path' => is_string( $path ) ? $path : '',
						);
					}
				}
			);
		}

		foreach ( $files as $file ) {
			if ( ! wpumpd_erase_file( $file['url'], $file['path'] ) ) {
				// translators: %s field name
				$messages[]     = sprintf( esc_html__( 'Your "%s" file was kept, as it may be in use elsewhere or could not be safely removed.', 'wpum-personal-data' ), $file['name'] );
				$items_retained = true;
			}
		}
	}

	return array(
		'items_removed'  => $items_removed,
		'items_retained' => $items_retained,
		'messages'       => $messages,
		'done'           => true,
	);

}
